func solveSudoku(board [][]byte) {
	solver := NewSudokuSolver(&board)
	solver.SolveIt()
}

func NewSudokuSolver(board *[][]byte) SudokuSolver {
	return SudokuSolver{
		board:           board,
		validCeilMatrix: make([]map[int]bool, 9),
		validColMatrix:  make([]map[int]bool, 9),
		validRowMatrix:  make([]map[int]bool, 9),
	}
}

func out(board [][]byte) {
	for rowI, _ := range board {
		for _, colV := range board[rowI] {
			print(string(colV))
			print(", ")
		}
		println()
	}
}
